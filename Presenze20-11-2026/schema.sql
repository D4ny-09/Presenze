-- 1. TABELLA ISCRITTI (Ragazzi, Catechisti e Animatori)
create table if not exists public.iscritti (
  id text primary key,
  nome text not null,
  cognome text not null,
  ruolo text default 'Bambino',
  anno text not null,
  iscritto_catechismo boolean default true,
  allergie text default '',
  deleghe text default '',
  note text default '',
  telefono text default '[]',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. TABELLA PRESENZE (Presenze giornaliere per data e iscritto)
create table if not exists public.presenze (
  id bigint generated by default as identity primary key,
  data text not null,
  iscritto_id text not null,
  catechismo boolean default false,
  oratorio boolean default false,
  messa boolean default false,
  uscito boolean default false,
  ora_uscita text default '',
  note_giorno text default '',
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  constraint uq_data_iscritto unique (data, iscritto_id)
);

-- Indici per velocizzare le ricerche
create index if not exists idx_presenze_data on public.presenze (data);
create index if not exists idx_iscritti_anno on public.iscritti (anno);

-- 3. ABILITA ROW LEVEL SECURITY (RLS)
alter table public.iscritti enable row level security;
alter table public.presenze enable row level security;

-- 4. CRIA POLICY DI ACCESSO PUBBLICO ANONIMO (Lettura, Inserimento, Modifica, Cancellazione)
drop policy if exists "Accesso pubblico completo iscritti" on public.iscritti;
create policy "Accesso pubblico completo iscritti"
  on public.iscritti
  for all
  to anon, authenticated
  using (true)
  with check (true);

drop policy if exists "Accesso pubblico completo presenze" on public.presenze;
create policy "Accesso pubblico completo presenze"
  on public.presenze
  for all
  to anon, authenticated
  using (true)
  with check (true);
